package main

import (
	"fmt"
	"html"
	"os"
	"strings"
)

// HTMLReport renders the audit as one self-contained page. It exists so a report
// can be saved and sent to someone else - a friend asking for help, or a forum
// post - instead of a screenshot of the UI.
func (r *Result) HTMLReport() string {
	var b strings.Builder
	esc := html.EscapeString

	b.WriteString(`<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>skyrim-audit report</title>
<style>
 body{margin:0;background:#0d1117;color:#e6edf3;font:15px/1.55 "Segoe UI",Roboto,Arial,sans-serif}
 .wrap{max-width:1000px;margin:0 auto;padding:26px 20px 60px}
 h1{font-size:22px;margin:0 0 4px}
 h1 span{color:#ff9d3c}
 .meta{color:#93a1b1;font-size:13px;margin-bottom:18px}
 .counts{display:flex;gap:22px;flex-wrap:wrap;margin:16px 0 24px}
 .counts div b{display:block;font-size:22px}
 .counts small{color:#93a1b1;text-transform:uppercase;letter-spacing:.06em;font-size:11px}
 table{width:100%;border-collapse:collapse;font-size:13.5px;margin-top:6px}
 th,td{text-align:left;padding:6px 8px;border-bottom:1px solid #202836;vertical-align:top}
 th{color:#93a1b1;font-size:12px;text-transform:uppercase;letter-spacing:.05em}
 code{font-family:Consolas,monospace;font-size:.86em;color:#c9d1d9}
 .err{color:#ff9b95}.warn{color:#e3b341}.info{color:#8cc2ff}
 h2{font-size:16px;margin:26px 0 6px}
 p{color:#c3cedb;margin:6px 0}
</style></head><body><div class="wrap">
`)
	fmt.Fprintf(&b, "<h1>skyrim<span>-audit</span> report</h1>\n")
	fmt.Fprintf(&b, "<div class=\"meta\">instance <code>%s</code> &middot; profile <code>%s</code>",
		esc(r.Instance), esc(r.Profile))
	if r.GameVersion != "" {
		fmt.Fprintf(&b, " &middot; Skyrim %s (%s)", esc(r.GameVersion), esc(r.GameEdition))
	}
	if r.GameData != "" {
		fmt.Fprintf(&b, "<br>Data <code>%s</code>", esc(r.GameData))
	}
	if r.SaveFile != "" {
		fmt.Fprintf(&b, "<br>newest save <code>%s</code> (%d plugins)", esc(r.SaveFile), r.SavePlugins)
	}
	b.WriteString("</div>\n")

	fmt.Fprintf(&b, `<div class="counts">
 <div><small>Errors</small><b class="err">%d</b></div>
 <div><small>Warnings</small><b class="warn">%d</b></div>
 <div><small>Improvements</small><b class="info">%d</b></div>
 <div><small>Full plugins</small><b>%d</b></div>
 <div><small>Light plugins</small><b>%d</b></div>
 <div><small>Plugins</small><b>%d listed</b></div>
</div>
`, r.Counts.Error, r.Counts.Warn, r.Counts.Info, r.Full, r.Light, r.Listed)

	if len(r.Findings) == 0 {
		b.WriteString("<p>No findings: the load order passed every check.</p>\n")
	} else {
		b.WriteString("<h2>Findings</h2><table><thead><tr><th>Severity</th><th>Code</th><th>Plugin</th><th>Detail</th><th>What to do</th></tr></thead><tbody>\n")
		for _, f := range r.Findings {
			fmt.Fprintf(&b, "<tr><td class=\"%s\">%s</td><td><code>%s</code></td><td>%s</td><td>%s</td><td>%s</td></tr>\n",
				esc(string(f.Severity)), esc(string(f.Severity)), esc(f.Code),
				esc(firstNonEmpty(f.Plugin, f.Mod)), esc(f.Detail), esc(f.Fix))
		}
		b.WriteString("</tbody></table>\n")
	}

	if len(r.ExpectedOverlaps) > 0 {
		fmt.Fprintf(&b, "<h2>Expected overrides (%d)</h2>\n<p>By design: the higher-priority mod requires the lower one, so its files win on purpose.</p><table><tbody>\n", len(r.ExpectedOverlaps))
		for _, o := range r.ExpectedOverlaps {
			fmt.Fprintf(&b, "<tr><td>%s over %s</td><td>%d file(s)</td><td>%s</td></tr>\n",
				esc(o.Winner), esc(o.Loser), o.Files, esc(o.Reason))
		}
		b.WriteString("</tbody></table>\n")
	}

	if len(r.BrokenPlugins) > 0 {
		fmt.Fprintf(&b, "<h2>Plugins that cannot load (%d)</h2><p>%s</p>\n",
			len(r.BrokenPlugins), esc(strings.Join(r.BrokenPlugins, ", ")))
	}

	b.WriteString("<p style=\"margin-top:26px;color:#6b7a8d;font-size:12.5px\">Generated by skyrim-audit. Plugin checks are offline; Nexus results are suggestions, not verified fixes.</p>\n</div></body></html>\n")
	return b.String()
}

// WriteHTMLReport saves the report and returns the path it wrote.
func (r *Result) WriteHTMLReport(path string) error {
	if path == "" {
		return fmt.Errorf("no report path given")
	}
	if err := os.WriteFile(path, []byte(r.HTMLReport()), 0o644); err != nil {
		return fmt.Errorf("write report: %w", err)
	}
	return nil
}
